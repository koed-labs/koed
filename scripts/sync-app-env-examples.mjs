#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const START_MARKER = "# BEGIN GENERATED APP ENV EXAMPLES";
export const END_MARKER = "# END GENERATED APP ENV EXAMPLES";

export const appEnvSources = [
  { label: "API", dir: "apps/api", prefix: "API" },
  { label: "Worker", dir: "apps/worker", prefix: "WORKER" },
  {
    label: "Embedding service",
    dir: "apps/embedding-service",
    prefix: "EMBEDDING"
  },
  {
    label: "Explorer",
    dir: "apps/explorer",
    prefix: "EXPLORER"
  }
];

const sharedRootKeyPrefixes = ["MEMORY_"];
const sharedRootKeys = new Set([
  "EMBEDDING_MODEL_KEY",
  "EMBEDDING_RERANKER_KEY"
]);

const splitEnvLine = (line) => {
  const match = /^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/.exec(line);
  return match ? { key: match[1], value: match[2] } : null;
};

const rootDirective = (line) => {
  const match = /^#\s*@root\s+(.+?)\s*$/.exec(line);
  return match ? match[1] : null;
};

const defaultRootKey = (key, prefix) => {
  const passThroughPrefixes = [
    "API_",
    "EXPLORER_",
    "WORKER_",
    "EMBEDDING_",
    "MEMORY_"
  ];
  if (passThroughPrefixes.some((passThrough) => key.startsWith(passThrough))) {
    return key;
  }
  if (key.startsWith(`${prefix}_`)) {
    return key;
  }
  return `${prefix}_${key}`;
};

const parseRootDirective = (directive) => {
  if (directive === "omit") {
    return { rootKey: null, rootValue: undefined };
  }

  const match = /^([A-Za-z_][A-Za-z0-9_]*)(?:=(.*))?$/.exec(directive);
  if (!match) {
    throw new Error(`Invalid @root directive: ${directive}`);
  }

  return {
    rootKey: match[1],
    rootValue: match[2]
  };
};

export const parseAppEnvExample = (contents, source) => {
  const entries = [];
  let pendingRoot = null;

  for (const line of contents.split(/\r?\n/)) {
    const directive = rootDirective(line);
    if (directive) {
      pendingRoot = directive;
      continue;
    }

    const entry = splitEnvLine(line);
    if (!entry) {
      continue;
    }

    const directiveConfig =
      pendingRoot === null
        ? {
            rootKey: defaultRootKey(entry.key, source.prefix),
            rootValue: undefined
          }
        : parseRootDirective(pendingRoot);
    const rootKey = directiveConfig.rootKey;
    pendingRoot = null;

    if (rootKey) {
      entries.push({
        appKey: entry.key,
        rootKey,
        value: directiveConfig.rootValue ?? entry.value,
        source: source.label
      });
    }
  }

  return entries;
};

export const collectAppEnvEntries = (rootDir, sources = appEnvSources) => {
  const seen = new Map();
  const entries = [];

  for (const source of sources) {
    const examplePath = path.join(rootDir, source.dir, ".env.example");
    const parsed = parseAppEnvExample(
      fs.readFileSync(examplePath, "utf8"),
      source
    );

    for (const entry of parsed) {
      const existing = seen.get(entry.rootKey);
      if (existing) {
        if (existing.value !== entry.value) {
          throw new Error(
            `Conflicting generated root env value for ${entry.rootKey}: ` +
              `${existing.source}/${existing.appKey}="${existing.value}" and ` +
              `${entry.source}/${entry.appKey}="${entry.value}"`
          );
        }
        continue;
      }
      seen.set(entry.rootKey, entry);
      entries.push(entry);
    }
  }

  return entries;
};

const isSharedRootEntry = (entry) =>
  sharedRootKeys.has(entry.rootKey) ||
  sharedRootKeyPrefixes.some((prefix) => entry.rootKey.startsWith(prefix));

export const renderGeneratedBlock = (entries) => {
  const sharedEntries = [];
  const bySource = new Map();
  for (const entry of entries) {
    if (isSharedRootEntry(entry)) {
      sharedEntries.push(entry);
      continue;
    }

    const sourceEntries = bySource.get(entry.source) ?? [];
    sourceEntries.push(entry);
    bySource.set(entry.source, sourceEntries);
  }

  const lines = [
    START_MARKER,
    "# Generated by `pnpm env:sync` from apps/*/.env.example.",
    "# Edit the app .env.example files, then rerun the sync script.",
    ""
  ];

  if (sharedEntries.length > 0) {
    lines.push("# Shared app config");
    for (const entry of sharedEntries) {
      lines.push(`${entry.rootKey}=${entry.value}`);
    }
    lines.push("");
  }

  for (const [source, sourceEntries] of bySource) {
    lines.push(`# ${source} app`);
    for (const entry of sourceEntries) {
      lines.push(`${entry.rootKey}=${entry.value}`);
    }
    lines.push("");
  }

  lines.push(END_MARKER);
  return lines.join("\n");
};

export const replaceGeneratedBlock = (rootContents, generatedBlock) => {
  const start = rootContents.indexOf(START_MARKER);
  const end = rootContents.indexOf(END_MARKER);

  if (start !== -1 || end !== -1) {
    if (start === -1 || end === -1 || end < start) {
      throw new Error(
        "Root .env.example has mismatched generated block markers."
      );
    }

    const afterEnd = end + END_MARKER.length;
    return `${rootContents.slice(0, start).replace(/\s*$/, "\n\n")}${generatedBlock}${rootContents
      .slice(afterEnd)
      .replace(/^\s*/, "\n\n")}`;
  }

  const localClientMarker = "# Local AI-client integration values.";
  const insertAt = rootContents.indexOf(localClientMarker);
  if (insertAt === -1) {
    return `${rootContents.replace(/\s*$/, "\n\n")}${generatedBlock}\n`;
  }

  return `${rootContents.slice(0, insertAt).replace(/\s*$/, "\n\n")}${generatedBlock}\n\n${rootContents.slice(insertAt)}`;
};

export const syncRootEnvExample = (rootDir) => {
  const rootExamplePath = path.join(rootDir, ".env.example");
  const entries = collectAppEnvEntries(rootDir);
  const generatedBlock = renderGeneratedBlock(entries);
  const current = fs.readFileSync(rootExamplePath, "utf8");
  const next = replaceGeneratedBlock(current, generatedBlock);
  return { rootExamplePath, current, next };
};

const main = () => {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const check = process.argv.includes("--check");
  const print = process.argv.includes("--print");
  const { rootExamplePath, current, next } = syncRootEnvExample(root);

  if (print) {
    process.stdout.write(next);
    return;
  }

  if (check) {
    if (current !== next) {
      console.error(
        ".env.example generated app block is out of date. Run `pnpm env:sync`."
      );
      process.exit(1);
    }
    console.log(".env.example generated app block is up to date.");
    return;
  }

  if (current !== next) {
    fs.writeFileSync(rootExamplePath, next);
    console.log("Updated .env.example generated app block.");
  } else {
    console.log(".env.example generated app block is already up to date.");
  }
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
